import argparse
import hashlib
from pathlib import Path
import struct

RESOURCE = Path(__file__).resolve().parents[1] / (
    "app/src/test/resources/snapshot_fingerprint_v1_golden.properties"
)
SALT = bytes(range(32))


def encode(value):
    if value is None:
        return struct.pack(">i", -1)
    # Java/Kotlin UTF-8 replaces an unpaired UTF-16 surrogate with ASCII '?'.
    payload = value.encode("utf-8", errors="replace")
    return struct.pack(">i", len(payload)) + payload


def node(path, view_id, class_name, bounds, clickable, enabled, children, actions, text, description):
    # Booleans/actions use literal V1 spellings, not Python's True/False or collection repr.
    return {
        "structure": [path, view_id, class_name, *map(str, bounds), clickable, enabled, str(children), actions],
        "content": [path, text, description],
        "outline": [path, view_id, class_name],
    }


def expected_resource():
    nodes = [
        node("0", None, "android.widget.FrameLayout", (0, 0, 1080, 1920), "false", "true", 2, "", None, ""),
        node("0/0", "synthetic:id/공지", "android.widget.TextView", (24, 60, 1056, 600),
             "false", "true", 0, "", "합성 점검 공지🙂", None),
        node("0/1", "", None, (-7, 640, 1001, 880), "true", "false", 0, "CLICK,DISMISS", "닫기", "합성 설명\n확인"),
    ]
    vectors = {
        "structure.empty": [],
        "content.empty": [],
        "structure.tree": [field for n in nodes for field in n["structure"]],
        "content.tree": [field for n in nodes for field in n["content"]],
        "structure.reordered": [field for n in reversed(nodes) for field in n["structure"]],
        "content.reordered": [field for n in reversed(nodes) for field in n["content"]],
        "application": ["kr.closeforyou.synthetic"],
        "outline.null_empty": ["0", None, ""],
        "outline.empty_null": ["0", "", None],
        "outline.utf8": ["0/0", "한글", "🙂"],
        "outline.swapped_fields": ["0/0", "🙂", "한글"],
        "outline.long_utf8": ["0", "가" * 86, None],
        "outline.unpaired_high": ["0", "\ud800", None],
        "outline.unpaired_low": ["0", "\udc00", None],
        "outline.decomposed": ["0/0", "한글", "🙂"],
    }
    for index, n in enumerate(nodes):
        vectors[f"outline.node{index}"] = n["outline"]
    for name, actions in [("none", ""), ("click", "CLICK"), ("dismiss", "DISMISS"), ("both", "CLICK,DISMISS")]:
        vectors[f"structure.actions.{name}"] = node(
            "0", None, "android.widget.FrameLayout", (0, 0, 1080, 1920),
            "false", "true", 0, actions, None, "",
        )["structure"]
    lines = [
        "# SYNTHETIC ONLY. Generated by tools/generate_snapshot_fingerprint_goldens.py --write",
        "# .stream = preimage after salt: concatenated int32-BE UTF-8 fields; .sha256 = SHA256(salt + stream)",
        "salt=" + SALT.hex(),
    ]
    for name, fields in sorted(vectors.items()):
        stream = b"".join(encode(field) for field in fields)
        lines.extend([name + ".stream=" + stream.hex(), name + ".sha256=" + hashlib.sha256(SALT + stream).hexdigest()])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate fixed synthetic golden resource")
    args = parser.parse_args()
    expected = expected_resource()
    if args.write:
        RESOURCE.parent.mkdir(parents=True, exist_ok=True)
        RESOURCE.write_text(expected, encoding="ascii")
        print("SYNTHETIC_GOLDENS_WRITTEN")
    elif RESOURCE.is_file() and RESOURCE.read_text(encoding="ascii") == expected:
        print("SYNTHETIC_GOLDENS_MATCH")
    else:
        raise SystemExit("SYNTHETIC_GOLDENS_MISMATCH")


if __name__ == "__main__":
    main()
